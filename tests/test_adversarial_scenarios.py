@pytest.mark.parametrize("mode", ["io", "commit", "busy"])
def test_a_persistence_failure_during_handout_never_publishes_a_lease(tmp_path, mode):
    """If the attempt is not durable, the worker must not be holding it."""
    harness = CoordinatorHarness(Path(tmp_path) / "state")
    try:
        execution_id = _open_network(harness, labels=("n0",))
        harness.enqueue_unit("u0", execution_id=execution_id, unit_id="candidate-u0")

        harness.faults.arm(target_index=3, mode=mode)
        try:
            response = harness.client.get(
                "/tasks/next", params={"node_id": "n0"}, headers=harness.headers("n0")
            )
        except Exception:
            response = None
        finally:
            harness.faults.disarm()

        durable = harness.durable_attempts()
        if response is not None and response.status_code == 200 and response.json().get("attempt_id"):
            assert response.json()["attempt_id"] in durable, (
                "a lease was handed out that no durable attempt backs"
            )
        else:
            assert durable == {}, "a durable attempt exists that no worker was told about"
    finally:
        harness.close()


