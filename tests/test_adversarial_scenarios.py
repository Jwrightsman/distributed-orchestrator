# ── 8. Crash between verification and settlement ─────────────────────


@pytest.mark.parametrize("fault_index", [0, 1, 2, 3, 4, 5, 6, 7, 8])
def test_a_crash_at_the_settlement_boundary_never_pays_without_accepting(tmp_path, fault_index):
    """Settlement, receipt, and credit are one transaction or none of it.

    A commit-time failure is the sharpest version of "crashed between deciding
    a result is good and recording that decision". Reconcile afterwards and the
    coordinator must still be able to say truthfully which of the two states it
    is in.
    """
    harness = CoordinatorHarness(Path(tmp_path) / "state")
    try:
        execution_id = _open_network(harness, labels=("n0",))
        handout = _lease(harness, execution_id, "u0")

        harness.faults.arm(target_index=fault_index, mode="commit")
        try:
            harness.submit("u0", harness.result_body(handout), label="n0")
        except Exception:
            pass
        finally:
            harness.faults.disarm()

        harness.restart()

        receipts = harness.durable_receipts()
        credits = harness.durable_credits()
        assert set(receipts) == set(credits), (
            f"a commit fault at index {fault_index} paid without accepting, or the reverse"
        )
        attempt = harness.durable_attempts()[handout.attempt_id]
        if receipts:
            assert attempt["state"] == "settled"
        else:
            assert attempt["state"] in ("interrupted", "active", "expired", "cancelled")
            assert attempt["state"] != "settled"

        # Whatever happened, the coordinator's answer is stable on re-reading.
        with sqlite3.connect(harness.database) as con:
            con.row_factory = sqlite3.Row
            settled = con.execute(
                "SELECT COUNT(*) AS n FROM attempts WHERE state = 'settled'"
            ).fetchone()["n"]
        assert settled == len(receipts)
    finally:
        harness.close()
